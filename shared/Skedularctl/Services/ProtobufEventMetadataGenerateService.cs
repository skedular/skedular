using System.Reflection;
using CommandLine;
using DotLiquid;

namespace Skedularctl.Services;

public enum BoolType
{
    False,
    True
}

[Verb("protobuf-event-metadata-generate", HelpText = "Generate metadata in addition to code generated by protobuf generated required by the app")]
public class ProtobufEventMetadataGenerateOptions
{
    [Option("namespace", Required = true, HelpText = "The namespace")]
    public string Namespace { get; set; } = string.Empty;

    [Option("event-type", Required = true, HelpText = "The event type")]
    public string EventType { get; set; } = string.Empty;

    [Option("topic-name", Required = true, HelpText = "Specify the topic name")]
    public string TopicName { get; set; } = string.Empty;

    [Option("topic-partition-count", Required = false, HelpText = "Specify the topic partition count")]
    public int TopicPartitionCount { get; set; } = 3;

    [Option("retry-topic-name-prefix", Required = true, HelpText = "Specify the retry topic name prefix")]
    public string RetryTopicNamePrefix { get; set; } = string.Empty;

    [Option("retry-topic-partition-count", Required = false, HelpText = "Specify the retry topic partition count")]
    public int RetryTopicPartitionCount { get; set; } = 3;

    [Option("retry-topic-count", Required = false, HelpText = "Specify the retry topic count")]
    public int RetryTopicCount { get; set; }

    [Option("dead-letter-topic-name", Required = true, HelpText = "Specify the dead letter topic name")]
    public string DeadLetterTopicName { get; set; } = string.Empty;

    [Option("dead-letter-topic-partition-count", Required = false,
        HelpText = "Specify the dead letter topic partition count")]
    public int DeadLetterTopicPartitionCount { get; set; } = 3;

    [Option("protobuf-schema-file-path", Required = true, HelpText = "Specify the protobuf schema file path")]
    public string ProtobufSchemaFilePath { get; set; } = string.Empty;

    [Option("generate-metadata-function-helper", Required = false, HelpText = "Generate Metadata Function Helper")]
    public BoolType GenerateMetadataFunctionHelper { get; set; } = BoolType.True;

    [Option("output-file-path", Required = true, HelpText = "Specify the output file path")]
    public string OutputFilePath { get; set; } = string.Empty;
}

public interface IProtobufEventMetadataGenerateService
{
    Task HandleAsync(ProtobufEventMetadataGenerateOptions options, CancellationToken cancellationToken);
}

public class ProtobufEventMetadataGenerateService : IProtobufEventMetadataGenerateService
{
    public async Task HandleAsync(ProtobufEventMetadataGenerateOptions options, CancellationToken cancellationToken)
    {
        ArgumentException.ThrowIfNullOrWhiteSpace(options.Namespace);
        ArgumentException.ThrowIfNullOrWhiteSpace(options.EventType);
        ArgumentException.ThrowIfNullOrWhiteSpace(options.TopicName);
        ArgumentException.ThrowIfNullOrWhiteSpace(options.RetryTopicNamePrefix);
        ArgumentException.ThrowIfNullOrWhiteSpace(options.DeadLetterTopicName);
        ArgumentException.ThrowIfNullOrWhiteSpace(options.ProtobufSchemaFilePath);
        ArgumentException.ThrowIfNullOrWhiteSpace(options.OutputFilePath);

        if (!File.Exists(options.ProtobufSchemaFilePath))
        {
            throw new ArgumentException($"File {options.ProtobufSchemaFilePath} does not exist.");
        }

        await using var stream = Assembly.GetExecutingAssembly()
            .GetManifestResourceStream(options.GenerateMetadataFunctionHelper == BoolType.True
                ? "Skedularctl.Events.Resources.EventMetadata.liquid"
                : "Skedularctl.Events.Resources.EventWithoutMetadata.liquid");
        ArgumentNullException.ThrowIfNull(stream);

        using var streamReader = new StreamReader(stream);
        var template = Template.Parse(await streamReader.ReadToEndAsync(cancellationToken));
        var assembly = Assembly.GetExecutingAssembly().GetName();

        var renderedContent = template.Render(Hash.FromAnonymousObject(new
        {
            tool = assembly.Name,
            version = assembly.Version?.ToString(),
            @namespace = options.Namespace,
            event_type = options.EventType,
            topic_name = options.TopicName,
            topic_partition_count = options.TopicPartitionCount,
            retry_topic_name_prefix = options.RetryTopicNamePrefix,
            retry_topic_name_count = options.RetryTopicCount,
            retry_topic_partition_count = options.RetryTopicPartitionCount,
            dead_letter_topic_name = options.DeadLetterTopicName,
            dead_letter_topic_partition_count = options.DeadLetterTopicPartitionCount,
            protobuf_schema = (await File.ReadAllTextAsync(options.ProtobufSchemaFilePath, cancellationToken))
                .Replace("\"", "\\\"")
                .Replace(Environment.NewLine, string.Empty)
        }));

        await File.WriteAllTextAsync(options.OutputFilePath, renderedContent, cancellationToken);
    }
}
